        <p>Попрощавшись із дітьми і провівши їх до виходу, пані Агата повернулась у дім, а трійця попрямувала назад у кафе в цілковитій тиші. Усередині, познімавши куртки, вони теж деякий час мовчали — лишень Марк роздивлявся, що йому дала пані Агата, і поспіхом робив нотатки в зошиті. Першою тишу порушила Яся.</p>

